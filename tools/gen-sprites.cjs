// Turns the asset pack's pixel-data.json + manifest.json into the mod's RLE
// modules under hooks/gen/. Run from the repo root: node tools/gen-sprites.cjs
//
// Each output is one `export const X: Record<string, PixelSprite>`; the key is
// the manifest id without its group prefix (angler/idle/0 -> idle/0). The RLE
// rows are the pack's own (a palette letter or '.', then its run length when
// over 1), the same encoding hunt-8bit's hooks/gen files use.
'use strict'
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const pack = path.join(root, 'fishing-mod-assets-v1')
const pixels = JSON.parse(fs.readFileSync(path.join(pack, 'pixel-data.json'), 'utf8')).sprites
const manifest = JSON.parse(fs.readFileSync(path.join(pack, 'manifest.json'), 'utf8'))
const outDir = path.join(root, 'hooks', 'gen')
fs.mkdirSync(outDir, { recursive: true })

/** The groups: output name, constant name, and which manifest ids go in (with the key they get). */
const GROUPS = [
  { file: 'angler', name: 'ANGLER', pick: id => (id.startsWith('angler/') ? id.slice('angler/'.length) : null) },
  { file: 'fish', name: 'FISH_SPRITES', pick: id => (id.startsWith('fish/') ? id.slice('fish/'.length) : null) },
  {
    file: 'scenes',
    name: 'SCENE_SPRITES',
    // the composite (all four layers) is the base; the foreground is drawn again over the actors
    pick: id => {
      const m = id.match(/^scene\/(\w+)\/(preview|foreground)$/)
      return m === null ? null : `${m[1]}/${m[2] === 'preview' ? 'base' : 'over'}`
    },
  },
  {
    file: 'gear',
    name: 'GEAR',
    pick: id => {
      if (id.startsWith('gear/rod/')) return `rod/${id.slice('gear/rod/'.length)}`
      if (id === 'gear/landing-net') return 'net'
      const lure = id.match(/^lure\/(\w+)(\/world)?$/)
      if (lure !== null) return `lure/${lure[1]}/${lure[2] === undefined ? 'icon' : 'world'}`
      if (id.startsWith('effect/')) return id
      return null
    },
  },
  {
    file: 'ui',
    name: 'UI',
    pick: id => {
      if (id.startsWith('ui/icon/')) return `icon/${id.slice('ui/icon/'.length)}`
      if (id === 'font/measurements') return 'font'
      if (id === 'ui/catch-panel') return 'catch-panel'
      return null
    },
  },
]

const SYMBOLS = /^[A-Za-z]$/
let total = 0
for (const group of GROUPS) {
  const out = {}
  for (const [id, meta] of Object.entries(manifest.sprites)) {
    const key = group.pick(id)
    if (key === null) continue
    const px = pixels[id]
    if (px === undefined) throw new Error(`no pixels for ${id}`)
    for (const sym of Object.keys(px.palette)) if (!SYMBOLS.test(sym)) throw new Error(`${id}: palette symbol ${sym} would read as a run length`)
    if (px.w !== meta.size[0] || px.h !== meta.size[1]) throw new Error(`${id}: size mismatch`)
    const sprite = { w: px.w, h: px.h, palette: px.palette, rows: px.rows }
    if (meta.anchors !== undefined) sprite.anchors = meta.anchors
    if (meta.facing !== undefined) sprite.facing = meta.facing
    if (meta.equipment !== undefined) sprite.equipment = meta.equipment
    out[key] = sprite
  }
  const keys = Object.keys(out)
  if (keys.length === 0) throw new Error(`${group.file}: nothing picked`)
  const body = keys.map(k => `${JSON.stringify(k)}:${JSON.stringify(out[k])}`).join(',\n')
  const text =
    `// Generated by tools/gen-sprites.cjs from fishing-mod-assets-v1 (manifest v${manifest.version}); do not edit.\n` +
    `import type { PixelSprite } from '../pixels'\n\n` +
    `export const ${group.name}: Readonly<Record<string, PixelSprite>> = {\n${body}\n}\n`
  const file = path.join(outDir, `${group.file}.ts`)
  fs.writeFileSync(file, text)
  total += keys.length
  console.log(`${path.relative(root, file)}: ${keys.length} sprites, ${(text.length / 1024).toFixed(0)} KB`)
}
console.log(`${total} sprites written`)
